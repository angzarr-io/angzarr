/// The one comment line every file the generator writes opens with, in
/// the file's own comment syntax: what the generator writes is the user's
/// to license as they choose.
pub const LICENCE_HEADER: &str =
    "Generated by angzarr-cli; you may license this file as you choose.";

/// What marks a file as the generator's, in its first lines
/// ([`MARKER_LINES`]): every generated file carries it, so a file without it
/// is never overwritten or deleted as the generator's.
pub const GENERATED_MARKER: &str = "@generated";

/// How many lines from the top [`is_generated`] reads for the marker.
pub const MARKER_LINES: usize = 5;

/// Whether `source` carries [`GENERATED_MARKER`] in its first
/// [`MARKER_LINES`] lines: a file the generator wrote.
pub fn is_generated(source: &str) -> bool {
    source
        .lines()
        .take(MARKER_LINES)
        .any(|line| line.contains(GENERATED_MARKER))
}

/// `source` opening with [`LICENCE_HEADER`] as a comment in `path`'s
/// syntax (`//` for Rust, `#` for Python, TOML and YAML), once: a source
/// that already opens with it, a user's file read back, is returned as it
/// is, as is one of another kind.
pub(crate) fn headed(path: &str, source: String) -> String {
    let marker = if path.ends_with(".rs") {
        "//"
    } else if [".py", ".toml", ".yaml", ".yml"]
        .iter()
        .any(|ext| path.ends_with(ext))
    {
        "#"
    } else {
        return source;
    };
    let line = format!("{marker} {LICENCE_HEADER}\n");
    if source.starts_with(&line) {
        return source;
    }
    line + &source
}

/// Every file of `files`, [`headed`].
pub(crate) fn headed_files(files: Vec<ScaffoldFile>) -> Vec<ScaffoldFile> {
    files
        .into_iter()
        .map(|f| ScaffoldFile {
            source: headed(&f.path, f.source),
            ..f
        })
        .collect()
}

