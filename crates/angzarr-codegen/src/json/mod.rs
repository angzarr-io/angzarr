//! The proto3 JSON of prost's wire types ([`json`]): the runtime
//! (`runtime.rs`, written verbatim), then for every message of the files'
//! packages, and every message they reach, its `JsonMessage` impl, and for
//! the files' own its `serde` impls. The canonical mapping, but where the
//! codegen options (`io.angzarr.codegen.v1`) say otherwise.

use proc_macro2::TokenStream;
use prost_reflect::{EnumDescriptor, FieldDescriptor, Kind, MessageDescriptor, OneofDescriptor};
use quote::{format_ident, quote};

use crate::common::{snake, upper_camel, wire_name};
use crate::error::{CodegenError, ProtoError, UseError};
use crate::model::{DURATION, TIMESTAMP, UUID};
use crate::options::{self, JsonField, JsonMessage};
use crate::rust::ident;

/// The runtime every generated file opens with.
const RUNTIME: &str = include_str!("runtime.rs");
const ANY: &str = "google.protobuf.Any";
/// angzarr's own package, whose prost types are angzarr-proto's.
const ANGZARR: &str = "io.angzarr.v1";

/// The proto3 JSON of the prost types of `files`' packages (`wire` names
/// each package's Rust path), as one file for a wire crate to `include!`
/// in a module of its own: see [`crate::CODEGEN_PROTO`] for the options
/// it reads.
pub fn json(
    descriptor_set: &[u8],
    files: &[&str],
    wire: &[(&str, &str)],
) -> Result<String, CodegenError> {
    let pool = crate::model::decode(descriptor_set)?;
    let mut packages: Vec<String> = Vec::new();
    for file in files {
        let found = pool
            .get_file_by_name(file)
            .ok_or_else(|| UseError::FileNotInSet {
                file: file.to_string(),
            })?;
        if !packages.contains(&found.package_name().to_string()) {
            packages.push(found.package_name().to_string());
        }
    }
    let mut messages: Vec<MessageDescriptor> = Vec::new();
    for message in pool.all_messages() {
        if packages.iter().any(|p| p == message.package_name()) {
            reach(&message, &mut messages)?;
        }
    }
    let at = Wire::of(wire);
    let mut enums: Vec<EnumDescriptor> = Vec::new();
    let mut items = TokenStream::new();
    for message in &messages {
        let local = packages.iter().any(|p| p == message.package_name());
        items.extend(implementation(message, &at, local, &mut enums)?);
    }
    for e in &enums {
        items.extend(enum_names(e));
    }
    let file: syn::File = syn::parse2(items).expect("the emitter writes valid Rust");
    Ok(crate::headed(
        ".rs",
        format!(
            "// @generated by angzarr-codegen from {}. Do not edit: every build rewrites it.\n\n{RUNTIME}\n{}",
            files.join(", "),
            prettyplease::unparse(&file)
        ),
    ))
}

/// `message` and every message it reaches, each once, in `out`; the
/// well-known types the runtime writes and angzarr's UUID left out, any
/// other well-known type refused.
fn reach(message: &MessageDescriptor, out: &mut Vec<MessageDescriptor>) -> Result<(), ProtoError> {
    if message.is_map_entry() || out.contains(message) {
        return Ok(());
    }
    out.push(message.clone());
    for field in message.fields() {
        let kind = match field.kind() {
            Kind::Message(entry) if entry.is_map_entry() => entry.map_entry_value_field().kind(),
            kind => kind,
        };
        if let Kind::Message(m) = kind {
            if written_by_runtime(&m) {
                continue;
            }
            if m.package_name() == "google.protobuf" {
                return Err(ProtoError::WellKnownType {
                    message: message.full_name().to_string(),
                    field: field.name().to_string(),
                    type_name: m.full_name().to_string(),
                });
            }
            reach(&m, out)?;
        }
    }
    Ok(())
}

/// A type the runtime writes itself: Timestamp, Duration, Any, UUID.
fn written_by_runtime(m: &MessageDescriptor) -> bool {
    [TIMESTAMP, DURATION, ANY, UUID].contains(&m.full_name())
}

/// The Rust paths of the packages' prost types.
struct Wire {
    paths: std::collections::BTreeMap<String, syn::Path>,
}

impl Wire {
    fn of(wire: &[(&str, &str)]) -> Wire {
        let mut paths: std::collections::BTreeMap<String, syn::Path> = wire
            .iter()
            .filter_map(|(p, rust)| {
                syn::parse_str::<syn::Path>(rust)
                    .ok()
                    .map(|path| (p.to_string(), path))
            })
            .collect();
        paths
            .entry(ANGZARR.to_string())
            .or_insert_with(|| syn::parse_quote!(::angzarr_proto::v1));
        Wire { paths }
    }

    /// The module prost declares `message`'s nested types in, or the
    /// package's for a top-level one, with `inner` its own module.
    fn module(&self, message: &MessageDescriptor) -> Result<TokenStream, UseError> {
        let wire = self
            .paths
            .get(message.package_name())
            .ok_or_else(|| UseError::NoWirePath {
                package: message.package_name().to_string(),
            })?;
        let mut modules: Vec<syn::Ident> = Vec::new();
        let mut parent = message.parent_message();
        while let Some(p) = parent {
            modules.push(ident(&snake(p.name())));
            parent = p.parent_message();
        }
        modules.reverse();
        Ok(quote!(#wire #(::#modules)*))
    }

    /// `message`'s prost type, or the runtime's for a type it writes.
    fn message(&self, message: &MessageDescriptor) -> Result<TokenStream, UseError> {
        match message.full_name() {
            TIMESTAMP => return Ok(quote!(::prost_types::Timestamp)),
            DURATION => return Ok(quote!(::prost_types::Duration)),
            ANY => return Ok(quote!(::prost_types::Any)),
            UUID => return Ok(quote!(::angzarr_proto::v1::Uuid)),
            _ => {}
        }
        let module = self.module(message)?;
        let name = ident(message.name());
        Ok(quote!(#module::#name))
    }

    /// prost's choice of `oneof`.
    fn choice(&self, oneof: &OneofDescriptor) -> Result<TokenStream, UseError> {
        let message = oneof.parent_message();
        let module = self.module(message)?;
        let inner = ident(&snake(message.name()));
        let name = ident(&upper_camel(oneof.name()));
        Ok(quote!(#module::#inner::#name))
    }
}

/// The constant of `e`'s names.
fn enum_const(e: &EnumDescriptor) -> syn::Ident {
    format_ident!("ENUM_{}", e.full_name().replace('.', "_").to_uppercase())
}

/// `e`'s names: each value's number, the name it is written as (its
/// `json_name`, else its kebab-case wire name under `JSON_CASE_KEBAB`, else
/// its proto name), and the names it is read from (that and its proto
/// name).
fn enum_names(e: &EnumDescriptor) -> TokenStream {
    let name = enum_const(e);
    let kebab = options::json_kebab(e);
    let values = e.values().map(|v| {
        let number = v.number();
        let renamed = options::json_value_name(&v);
        let written = if !renamed.is_empty() {
            renamed
        } else if kebab {
            wire_name(e, v.name()).to_lowercase().replace('_', "-")
        } else {
            v.name().to_string()
        };
        let proto = v.name();
        quote!((#number, #written, &[#written, #proto]))
    });
    quote! {
        #[doc(hidden)]
        pub const #name: EnumNames = EnumNames { values: &[#(#values),*] };
    }
}

/// How one field of a message is keyed and written.
struct Key {
    /// The key it is written under.
    written: String,
    /// Every key it is read from.
    read: Vec<String>,
}

impl Key {
    fn of(field: &FieldDescriptor, json: &JsonField, message: &JsonMessage) -> Key {
        let written = if !json.key.is_empty() {
            json.key.clone()
        } else if message.proto_names {
            field.name().to_string()
        } else {
            field.json_name().to_string()
        };
        let mut read = vec![written.clone()];
        for other in [field.name(), field.json_name()] {
            if !read.iter().any(|r| r == other) {
                read.push(other.to_string());
            }
        }
        Key { written, read }
    }
}

/// One value of `kind`, at `value` (a reference), as JSON: the
/// expression, and whether it is a `Result` (a message's).
fn write_value(
    kind: &Kind,
    value: TokenStream,
    wire: &Wire,
    enums: &mut Vec<EnumDescriptor>,
) -> Result<(TokenStream, bool), UseError> {
    Ok(match kind {
        Kind::Int32 | Kind::Sint32 | Kind::Sfixed32 => (quote!(int(*#value)), false),
        Kind::Uint32 | Kind::Fixed32 => (quote!(uint(*#value)), false),
        Kind::Int64 | Kind::Sint64 | Kind::Sfixed64 | Kind::Uint64 | Kind::Fixed64 => {
            (quote!(long(*#value)), false)
        }
        Kind::Double => (quote!(double(*#value)), false),
        Kind::Float => (quote!(float(*#value)), false),
        Kind::Bool => (quote!(boolean(*#value)), false),
        Kind::String => (quote!(string(#value)), false),
        Kind::Bytes => (quote!(bytes(#value)), false),
        Kind::Enum(e) => {
            if !enums.contains(e) {
                enums.push(e.clone());
            }
            let names = enum_const(e);
            (quote!(#names.write(*#value)), false)
        }
        Kind::Message(m) => {
            let ty = wire.message(m)?;
            (
                quote!(<#ty as JsonMessage>::to_json(#value, registry)),
                true,
            )
        }
    })
}

/// One value of `kind` read from `value` (a `&Json`) at `at` (a `&str`):
/// a `Result`.
fn read_value(kind: &Kind, value: TokenStream, wire: &Wire) -> Result<TokenStream, UseError> {
    Ok(match kind {
        Kind::Int32 | Kind::Sint32 | Kind::Sfixed32 => quote!(read_int::<i32>(#value, &at)),
        Kind::Uint32 | Kind::Fixed32 => quote!(read_int::<u32>(#value, &at)),
        Kind::Int64 | Kind::Sint64 | Kind::Sfixed64 => quote!(read_int::<i64>(#value, &at)),
        Kind::Uint64 | Kind::Fixed64 => quote!(read_int::<u64>(#value, &at)),
        Kind::Double => quote!(read_double(#value, &at)),
        Kind::Float => quote!(read_float(#value, &at)),
        Kind::Bool => quote!(read_bool(#value, &at)),
        Kind::String => quote!(read_string(#value, &at)),
        Kind::Bytes => quote!(read_bytes(#value, &at)),
        Kind::Enum(e) => {
            let names = enum_const(e);
            quote!(#names.read(#value, &at))
        }
        Kind::Message(m) => {
            let ty = wire.message(m)?;
            quote!(<#ty as JsonMessage>::from_json(#value, registry).map(own))
        }
    })
}

/// Whether a message value of `kind` is written as an object of its own
/// fields: what a flattened field and a tagged oneof's arm need.
fn is_object(kind: &Kind) -> bool {
    matches!(kind, Kind::Message(m) if !written_by_runtime(m))
}

/// The writing and the reading of one field (or one oneof), and its
/// local's name.
struct Part {
    write: TokenStream,
    read: TokenStream,
    name: syn::Ident,
    local: syn::Ident,
    /// Whether it writes or reads a message, through the registry.
    registry: bool,
}

fn field_part(
    field: &FieldDescriptor,
    message: &JsonMessage,
    wire: &Wire,
    enums: &mut Vec<EnumDescriptor>,
) -> Result<Part, CodegenError> {
    let json = options::json_field(field);
    let Key { written, read } = Key::of(field, &json, message);
    let name = ident(field.name());
    let local = format_ident!("field_{}", field.name());
    let defaults = message.defaults;
    let null = json.null || message.nulls;
    let push = |value: TokenStream| quote!(out.push((#written.to_string(), #value)););
    let take = quote! {
        let at = fields.at(#written);
        if let Some(value) = fields.take(&[#(#read),*])?
    };
    let take_message = quote! {
        if let Some(value) = fields.take(&[#(#read),*])?
    };
    if json.flatten {
        return flatten_part(field, wire, name, local);
    }
    let kind = field.kind();
    if field.is_map() || field.is_list() {
        let (value_kind, write, read) = match &kind {
            Kind::Message(entry) if field.is_map() => (
                entry.map_entry_value_field().kind(),
                quote!(map),
                quote!(read_map),
            ),
            _ => (kind.clone(), quote!(list), quote!(read_list)),
        };
        let (each, fallible) = write_value(&value_kind, quote!(v), wire, enums)?;
        let each = if fallible { each } else { quote!(Ok(#each)) };
        let reading = read_value(&value_kind, quote!(v), wire)?;
        let written = push(quote!(#write(&self.#name, |v| #each)?));
        return Ok(Part {
            write: if defaults {
                written
            } else {
                quote!(if !self.#name.is_empty() { #written })
            },
            read: quote! {
                #take {
                    #local = #read(value, &at, |v| #reading)?;
                }
            },
            name,
            local,
            registry: matches!(value_kind, Kind::Message(_)),
        });
    }
    let (value, fallible) = write_value(&kind, quote!(value), wire, enums)?;
    let value = if fallible { quote!(#value?) } else { value };
    let reading = read_value(&kind, quote!(value), wire)?;
    let presence = field.supports_presence();
    let write = if presence {
        let written = push(value);
        if null {
            let unset = push(quote!(Json::Null));
            quote! {
                match &self.#name {
                    Some(value) => { #written }
                    None => { #unset }
                }
            }
        } else {
            quote! {
                if let Some(value) = &self.#name {
                    #written
                }
            }
        }
    } else {
        let written = push(value);
        if defaults {
            quote!({ let value = &self.#name; #written })
        } else {
            quote! {
                if !is_default(&self.#name) {
                    let value = &self.#name;
                    #written
                }
            }
        }
    };
    let message_kind = matches!(kind, Kind::Message(_));
    let take = if message_kind { take_message } else { take };
    let read = if presence {
        quote!(#take { #local = Some(#reading?); })
    } else {
        quote!(#take { #local = #reading?; })
    };
    Ok(Part {
        write,
        read,
        name,
        local,
        registry: message_kind,
    })
}

/// A field declaring `json_flatten`: its message's fields written into
/// its parent's object, and read from it; refused on any other field.
fn flatten_part(
    field: &FieldDescriptor,
    wire: &Wire,
    name: syn::Ident,
    local: syn::Ident,
) -> Result<Part, CodegenError> {
    let refused = || ProtoError::JsonFlatten {
        message: field.parent_message().full_name().to_string(),
        field: field.name().to_string(),
    };
    let Kind::Message(m) = field.kind() else {
        return Err(refused().into());
    };
    if field.is_list() || field.is_map() || !is_object(&field.kind()) {
        return Err(refused().into());
    }
    let ty = wire.message(&m)?;
    Ok(Part {
        write: quote! {
            if let Some(value) = &self.#name {
                value.write_fields(out, registry)?;
            }
        },
        read: quote! {
            let before = fields.taken();
            let flattened = <#ty as JsonMessage>::read_fields(fields, registry)?;
            if fields.taken() > before {
                #local = Some(own(flattened));
            }
        },
        name,
        local,
        registry: true,
    })
}

fn oneof_part(
    oneof: &OneofDescriptor,
    message: &JsonMessage,
    wire: &Wire,
    enums: &mut Vec<EnumDescriptor>,
) -> Result<Part, CodegenError> {
    let name = ident(oneof.name());
    let local = format_ident!("field_{}", oneof.name());
    let choice = wire.choice(oneof)?;
    let tag_key = options::json_choice_key(oneof);
    let mut writes = Vec::new();
    let mut reads = Vec::new();
    let registry = oneof.fields().any(|f| matches!(f.kind(), Kind::Message(_)));
    for field in oneof.fields() {
        let json = options::json_field(&field);
        let Key { written, read } = Key::of(&field, &json, message);
        let variant = ident(&upper_camel(field.name()));
        let kind = field.kind();
        let (value, fallible) = write_value(&kind, quote!(value), wire, enums)?;
        let value = if fallible { quote!(#value?) } else { value };
        let reading = read_value(&kind, quote!(value), wire)?;
        if tag_key.is_empty() {
            writes.push(quote! {
                Some(#choice::#variant(value)) => out.push((#written.to_string(), #value)),
            });
            reads.push(quote! {
                let at = fields.at(#written);
                if let Some(value) = fields.take(&[#(#read),*])? {
                    if is_set(&#local) {
                        return Err(JsonError::Duplicate { at, key: #written.to_string() });
                    }
                    #local = Some(#choice::#variant(#reading?));
                }
            });
            continue;
        }
        // A type the runtime writes declares no tag of its own: its arm's
        // tag is the arm's key, as a scalar's is.
        let tag = match &kind {
            Kind::Message(m) => {
                let own_tag = options::json_message(m).tag;
                if own_tag.is_empty() { written } else { own_tag }
            }
            _ => written,
        };
        if is_object(&kind) {
            let Kind::Message(m) = &kind else {
                unreachable!("an object is a message")
            };
            let ty = wire.message(m)?;
            writes.push(quote! {
                Some(#choice::#variant(value)) => {
                    out.push((#tag_key.to_string(), string(#tag)));
                    value.write_fields(out, registry)?;
                }
            });
            reads.push(quote! {
                #tag => #choice::#variant(own(<#ty as JsonMessage>::read_fields(fields, registry)?)),
            });
        } else {
            writes.push(quote! {
                Some(#choice::#variant(value)) => {
                    out.push((#tag_key.to_string(), string(#tag)));
                    out.push(("value".to_string(), #value));
                }
            });
            reads.push(quote! {
                #tag => {
                    let at = fields.at("value");
                    let value = fields
                        .take(&["value"])?
                        .ok_or_else(|| JsonError::Invalid { at: at.clone(), expected: "value" })?;
                    #choice::#variant(#reading?)
                }
            });
        }
    }
    let write = quote! {
        match &self.#name {
            #(#writes)*
            None => {}
        }
    };
    let read = if tag_key.is_empty() {
        quote!(#(#reads)*)
    } else {
        quote! {
            let at = fields.at(#tag_key);
            if let Some(tag) = fields.take(&[#tag_key])? {
                #local = Some(match read_string(tag, &at)?.as_str() {
                    #(#reads)*
                    other => return Err(JsonError::UnknownEnum { at, name: other.to_string() }),
                });
            }
        }
    };
    Ok(Part {
        write,
        read,
        name,
        local,
        registry,
    })
}

/// `message`'s `JsonMessage` impl, and, when it is of the files' own
/// packages (`local`), its `serde` impls.
fn implementation(
    message: &MessageDescriptor,
    wire: &Wire,
    local: bool,
    enums: &mut Vec<EnumDescriptor>,
) -> Result<TokenStream, CodegenError> {
    let ty = wire.message(message)?;
    let full = message.full_name();
    let options = options::json_message(message);
    let mut parts: Vec<Part> = Vec::new();
    let mut seen: Vec<OneofDescriptor> = Vec::new();
    for field in message.fields() {
        match field.containing_oneof() {
            Some(oneof) if !oneof.is_synthetic() => {
                if !seen.contains(&oneof) {
                    parts.push(oneof_part(&oneof, &options, wire, enums)?);
                    seen.push(oneof);
                }
            }
            _ => parts.push(field_part(&field, &options, wire, enums)?),
        }
    }
    let tag = if options.tag_key.is_empty() || options.tag.is_empty() {
        quote!()
    } else {
        let (key, tag) = (&options.tag_key, &options.tag);
        quote! {
            fn tag() -> Option<(&'static str, &'static str)> {
                Some((#key, #tag))
            }
        }
    };
    let writes = parts.iter().map(|p| &p.write);
    let reads = parts.iter().map(|p| &p.read);
    let locals = parts.iter().map(|p| &p.local);
    let assigned = parts.iter().map(|p| {
        let (name, local) = (&p.name, &p.local);
        quote!(#name: #local)
    });
    let (out, fields) = if parts.is_empty() {
        (quote!(_out), quote!(_fields))
    } else {
        (quote!(out), quote!(fields))
    };
    let registry = if parts.iter().any(|p| p.registry) {
        quote!(registry)
    } else {
        quote!(_registry)
    };
    let serde = if local {
        quote! {
            impl ::serde::Serialize for #ty {
                fn serialize<S: ::serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                    serialize(self, serializer)
                }
            }

            impl<'de> ::serde::Deserialize<'de> for #ty {
                fn deserialize<D: ::serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                    deserialize(deserializer)
                }
            }
        }
    } else {
        quote!()
    };
    Ok(quote! {
        impl JsonMessage for #ty {
            const NAME: &'static str = #full;

            #tag

            fn write_fields(&self, #out: &mut Vec<(String, Json)>, #registry: &Registry) -> Result<(), JsonError> {
                #(#writes)*
                Ok(())
            }

            fn read_fields(#fields: &mut Fields, #registry: &Registry) -> Result<Self, JsonError> {
                #(let mut #locals = ::core::default::Default::default();)*
                #(#reads)*
                Ok(Self { #(#assigned),* })
            }
        }

        #serde
    })
}
